package io.github.stream29.langchain4kt.api.openai.chat


import io.github.stream29.proxy.relocate.com.aallam.openai.api.chat.ToolCall
import io.github.stream29.langchain4kt.api.openai.chat.internal.ContentSerializer
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlin.jvm.JvmInline


/**
 * The messages to generate chat completions for.
 */
@Serializable
public data class ChatMessage(
    /**
     * The role of the author of this message.
     */
    public  val role: String,

    /**
     * The contents of the message.
     * **This is required for requests, and optional for responses**.
     */
    @SerialName("content")public  val messageContent: Content? = null,

    /**
     * The author's name of this message.
     * [name] is required if the role is `ChatRole.Function`, and it should be the name of the function whose response is
     * in the [content]. It May contain a-z, A-Z, 0-9, and underscores, with a maximum length of 64 characters.
     */
    @SerialName("name")public  val name: String? = null,

    /**
     * The name and arguments of a function that should be called, as generated by the model.
     */
    @Deprecated(message = "Deprecated in favor of toolCalls")
    @SerialName("function_call")public  val functionCall: FunctionCall? = null,

    /**
     * The tool calls generated by the model, such as function calls.
     */
    @SerialName("tool_calls")public  val toolCalls: List<ToolCall>? = null,

    /**
     * Tool call ID.
     */
    @SerialName("tool_call_id")public  val toolCallId: String? = null,

    /**
     * Azure Content Filter Results
     */
    @SerialName("content_filter_results")public  val contentFilterResults: List<ContentFilterResults>? = null,

    /**
     * Azure Content Filter Offsets
     */
    @SerialName("content_filter_offsets")public  val contentFilterOffsets: List<ContentFilterOffsets>? = null,
)

/**
 * The contents of the chat message.
 */
@Serializable(with = ContentSerializer::class)
public sealed interface Content

/**
 * The chat message content as text.
 */
@JvmInline
@Serializable
public value class TextContent(public val content: String) : Content

/**
 *  The chat message content as a list of content parts.
 */
@JvmInline
@Serializable
public value class ListContent(public val content: List<ContentPart>) : Content

/**
 * Represents a chat message part.
 */
@Serializable
public sealed interface ContentPart

/**
 * Text content part.
 *
 * @param text the text content.
 */
@Serializable
@SerialName("text")
public data class TextPart(@SerialName("text")public  val text: String) : ContentPart


